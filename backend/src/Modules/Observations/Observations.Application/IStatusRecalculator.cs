namespace Observations.Application;

/// <summary>
/// Пересчёт проекции <c>current_statuses</c> для фиксации. Пересчёт идёт
/// из таблицы <c>observations</c> целиком, а не инкрементально, поэтому итог не зависит от того,
/// в каком порядке приходили наблюдения и кто успел записать проекцию первым.
/// </summary>
/// <remarks>
/// Сериализация по фиксации — <c>pg_advisory_xact_lock(hashtext(mapObjectId::text))</c>:
/// одновременные вызовы для одной фиксации выполняются по очереди, а факты читаются уже после
/// взятия блокировки (иначе в проекцию могло бы попасть не самое свежее наблюдение — Review Focus 2).
/// Метод работает и внутри уже открытой транзакции вызывающего (отметка, отзыв), и самостоятельно.
/// </remarks>
public interface IStatusRecalculator
{
    /// <summary>
    /// Пересчитывает и записывает итоговый статус фиксации. <c>updated_at</c> обновляется только
    /// при изменении итога, чтобы ETag не менялся без причины. Если актуальных наблюдений нет,
    /// строка проекции создаётся со статусом «неизвестно» и свежестью <c>stale</c>.
    /// </summary>
    /// <param name="mapObjectId">Фиксация, для которой пересчитывается проекция.</param>
    /// <param name="now">Серверное время пересчёта; истёкшие наблюдения отбрасываются по нему.</param>
    /// <param name="ct">Токен отмены.</param>
    Task RecalculateAsync(Guid mapObjectId, DateTimeOffset now, CancellationToken ct);
}
