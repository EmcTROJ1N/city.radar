namespace Sources.Contracts;

/// <summary>
/// Системный источник «Сайт»: ровно один на категорию. Он не привязывается к фиксациям явно,
/// а доступен неявно каждой фиксации своей категории. Каталог вызывает провижионер при
/// создании и переименовании категории, поэтому источник, политика и статусы пишутся в той же
/// транзакции, что и сама категория.
/// </summary>
public interface ISiteSourceProvisioner
{
    /// <summary>
    /// Создаёт «Сайт» категории, если его ещё нет, и синхронизирует недостающие статусы из
    /// справочника категории. Существующий «Сайт» переименовывается вместе с категорией;
    /// его собственные статусы не перезаписываются. Изменения попадают в change tracker,
    /// <c>SaveChanges</c> вызывает вызывающая сторона.
    /// </summary>
    /// <param name="categoryId">Идентификатор категории.</param>
    /// <param name="categoryName">Текущее название категории.</param>
    /// <param name="ct">Токен отмены.</param>
    Task EnsureForCategoryAsync(Guid categoryId, string categoryName, CancellationToken ct);
}
